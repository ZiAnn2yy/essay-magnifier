/**
 * 危机信号规则引擎。
 *
 * 规范§四.4：遇到学生表达自伤/心理危机倾向，必须引导寻求专业帮助，
 * 不得自行"诊断"或"治疗"。
 *
 * 设计要点：判定完全由本文件的规则做出，在调用模型之前就跑完；
 * 命中后往消息序列注入强制指令，**模型无权覆盖**。
 * 这与 dogdog 的 triage() 是同一种架构——规则拥有结论，模型只负责措辞。
 *
 * ⚠️ 待办：下面的词表只是起点，上线前必须请指导教师或心理健康专业人士审定。
 * 漏判的代价是学生得不到引导；误判的代价是正常表达被打断，两边都要防。
 */

const CRISIS_RULES = [
  {
    id: 'self_harm_intent',
    // 注意措辞精度：「不想活了」才是危机表达，
    // 而「不想活成父母希望的样子」是身份抱怨——漏写这个「了」就会误触发。
    // 这类边界由 eval 的 safety-002 兜着，改词表后必须重跑。
    pattern: /(自杀|自尽|轻生|自残|不想活了|活不下去|结束自己的生命|伤害自己|割腕|跳楼|上吊)/,
    guidance: '停止一切学科内容，用平实关心的语气回应，明确引导寻求专业帮助',
  },
];

/** 在调模型之前判定。返回 level 与命中的规则 id，不返回原文片段（避免进日志外泄） */
export function detectCrisis(text) {
  const matched = CRISIS_RULES.filter((rule) => rule.pattern.test(text)).map((rule) => rule.id);
  return {
    level: matched.length > 0 ? 'crisis' : 'none',
    matched,
  };
}

