/**
 * 所有词按长度倒序查——否则「金光闪闪」会被「金光」抢先匹配，
 * 「香气扑鼻」会被「香气」截断，长的那个才是更好的词。
 */
const LEXICON = [
  ...FOUR_CHAR,
  ...COLOR,
  ...REDUPLICATED,
  ...SMELL,
  ...SOUND,
  ...ACTION,
  ...LIGHT,
].sort((a, b) => b.length - a.length);

/** 一次最多挑几个。三个是银幕上放得下又不杂的数。 */
const MAX_PICKS = 3;

/**
 * 从一句话里挑出"能变成画面"的词。
 *
 * 规则：长词优先、不重复、不重叠、最多三个。
 * 这是规则近似，不是语义理解——它挑得出的前提是孩子真的用了好词。
 * 孩子写「今天我很开心」，这里挑不出东西，那种情况该由大模型来问
 * 「怎么个开心法」，规则引擎不装懂。
 *
 * @param {string} sentence 孩子写的句子
 * @returns {string[]} 挑中的词，可能为空数组
 */
export function pickWords(sentence) {
  if (typeof sentence !== 'string' || sentence.trim().length === 0) return [];

  const text = sentence;
  const picked = [];
  // 已占用的字符区间，避免「金黄」和「金灿灿」在同一处重复命中
  const taken = [];

  for (const word of LEXICON) {
    if (picked.length >= MAX_PICKS) break;

    let from = 0;
    for (;;) {
      const index = text.indexOf(word, from);
      if (index === -1) break;
      from = index + word.length;

      const overlaps = taken.some(
        (span) => index < span.end && index + word.length > span.start,
      );
      if (overlaps) continue;

      taken.push({ start: index, end: index + word.length });
      picked.push({ word, index });
      break; // 同一个词只挑第一次出现
    }
  }

  // 按在句子里出现的顺序返回，而不是按词库分类顺序——
  // 银幕上的荧光笔要顺着读句子的方向亮过去
  return picked.sort((a, b) => a.index - b.index).map((item) => item.word);
}

/** 词库规模，给"题库/词库有多少内容"这类说明用。 */
export function getLexiconSize() {
  return LEXICON.length;
}
